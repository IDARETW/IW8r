QString qs(const std::string& s) { return QString::fromStdString(s); }

// Stock IW8 entity classes and their keys, generated by `iw8r iw8-classes` from Replay 1.20 MapEnts.
const QJsonObject& stockClasses() {
    static const QJsonObject classes = [] {
        QDir d(QCoreApplication::applicationDirPath());
        for (int up = 0; up < 3; ++up, d.cdUp()) {
            QFile f(d.filePath("data/iw8_entity_classes.json"));
            if (f.open(QIODevice::ReadOnly)) return QJsonDocument::fromJson(f.readAll()).object().value("classes").toObject();
        }
        return QJsonObject();
    }();
    return classes;
}
