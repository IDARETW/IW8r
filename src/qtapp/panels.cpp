int EntityInspector::rowForKey(const QString& key) const {
    for (int r = 0; r < table_->rowCount(); ++r)
        if (table_->item(r, 0) && table_->item(r, 0)->text() == key) return r;
    return -1;
}

QString EntityInspector::refusalFor(const QString& key, const QString& value) const {
    // Empty values are left alone, as refresh() does not tint them: a required key that is empty is listed as missing.
    if (value.trimmed().isEmpty()) return {};
    const Entity* e = ctx_->doc.findEntity(shownEntity_);
    const ClassDef* def = e ? entityDefs().find(e->classname()) : nullptr;
    const KeyDef* kd = def ? def->key(key.toStdString()) : nullptr;
    const QString problem = kd ? valueProblem(kd->type, value.toStdString()) : QString();
    return problem.isEmpty() ? QString() : QString("%1 is a %2 key and expects %3, not \"%4\"").arg(key, qs(kd->type), problem, value);
}

void EntityInspector::commitCell(int row, int column) {
    if (filling_ || column != 1) return;
    const QTableWidgetItem* k = table_->item(row, 0);
    QTableWidgetItem* v = table_->item(row, 1);
    if (!k || !v) return;
    // The entity the rows belong to: refresh() is skipped while a cell editor is open, so the inspected entity may
    // already be another one (a shortcut or the web API changed the selection meanwhile).
    const Id e = shownEntity_;
    const QString key = k->text();
    if (const QString why = refusalFor(key, v->text()); !why.isEmpty()) {
        // Refused: the cell goes back to the stored value and the status bar says what the key expects.
        const Entity* ent = ctx_->doc.findEntity(e);
        const std::string* stored = ent ? ent->value(key.toStdString()) : nullptr;
        filling_ = true;
        v->setText(stored ? qs(*stored) : QString());
        filling_ = false;
        ctx_->setStatus("Not set: " + why);
    } else if (ctx_->doc.setKeyValue(e, key.toStdString(), v->text().toStdString())) {
        ctx_->documentEdited("Set \"" + key + "\"");
    }
    // The selection moved on while the editor was open: show the inspected entity once the editor has closed.
    if (e != ctx_->doc.inspectedEntity()) QTimer::singleShot(0, this, [this] { refresh(); });
}

bool EntityInspector::removeSelectedKeys() {
    std::set<int> rows;
    for (const QModelIndex& i : table_->selectionModel()->selectedIndexes()) rows.insert(i.row());
    if (rows.empty() && table_->currentRow() >= 0) rows.insert(table_->currentRow());
    QStringList keys;
    for (int r : rows)
        if (const QTableWidgetItem* k = table_->item(r, 0); k && k->text() != "classname") keys << k->text();
    if (keys.isEmpty()) return false;
    // The same removal as the row's x button, all the keys in one undo step.
    const Id e = shownEntity_;
    ctx_->doc.beginGroup(keys.size() == 1 ? "Removed \"" + keys.front().toStdString() + "\"" : "Remove Keys");
    bool any = false;
    for (const QString& k : keys) any |= ctx_->doc.removeKey(e, k.toStdString());
    ctx_->doc.endGroup();
    if (any) ctx_->documentEdited(keys.size() == 1 ? "Removed \"" + keys.front() + "\"" : QString("Removed %1 keys").arg(keys.size()));
    return any;
}

bool EntityInspector::eventFilter(QObject* watched, QEvent* event) {
    if (watched == table_ && (event->type() == QEvent::ShortcutOverride || event->type() == QEvent::KeyPress)) {
        auto* ke = static_cast<QKeyEvent*>(event);
        // Not while a cell editor has the focus (Delete edits its text then), the same test as refresh().
        QWidget* fw = QApplication::focusWidget();
        const bool editing = fw && fw != table_ && table_->isAncestorOf(fw);
        // Delete, and Backspace (the default Delete Selection key), remove the selected keys here, never the entity.
        if ((ke->key() == Qt::Key_Delete || ke->key() == Qt::Key_Backspace) && (ke->modifiers() & ~Qt::KeypadModifier) == Qt::NoModifier &&
            !editing) {
            // Taken before the shortcuts: Delete bound to Delete Selection must not remove the entity from here.
            if (event->type() == QEvent::ShortcutOverride) event->accept();
            else removeSelectedKeys();
            return true;
        }
    }
    return QWidget::eventFilter(watched, event);
}

void EntityInspector::setLightColor(double r, double g, double b) {
    const Id e = ctx_->doc.inspectedEntity();
    const std::string v = formatNumber(clamp01(r)) + " " + formatNumber(clamp01(g)) + " " + formatNumber(clamp01(b));
    if (ctx_->doc.setKeyValue(e, "_color", v)) ctx_->documentEdited("Set \"_color\"");
}

void EntityInspector::showMissing(const std::vector<const KeyDef*>& missing, Id eid) {
    while (QLayoutItem* item = missingLay_->takeAt(0)) {
        if (QWidget* w = item->widget()) {
            // Detach first so findChild never sees the old button; deleteLater because a click may come from it.
            w->hide();
            w->setParent(nullptr);
            w->deleteLater();
        }
        delete item;
    }
    missing_.clear();
    for (const KeyDef* k : missing) {
        const QString name = qs(k->name);
        missing_ << name;
        auto* row = new QWidget(missingBox_);
        auto* rowLay = new QHBoxLayout(row);
        rowLay->setContentsMargins(0, 0, 0, 0);
        auto* label = new QLabel(row);
        label->setTextFormat(Qt::RichText);
        label->setWordWrap(true);
        rowLay->addWidget(label, 1);
        if (const std::optional<std::string> dv = defaultFor(*k)) {
            label->setText(QString("<span style='color:#c0392b'>Missing required key <b>%1</b></span>").arg(name.toHtmlEscaped()));
            auto* add = new QPushButton("Add", row);
            add->setObjectName("addMissing_" + name);
            add->setToolTip(QString("Add %1 = %2").arg(name, qs(*dv)));
            const std::string key = k->name;
            const std::string value = *dv;
            connect(add, &QPushButton::clicked, this, [this, eid, key, value, name] {
                if (ctx_->doc.setKeyValue(eid, key, value)) ctx_->documentEdited(QString("Added \"%1\"").arg(name));
            });
            rowLay->addWidget(add);
        } else {
            label->setText(QString("<span style='color:#c0392b'>Missing required key <b>%1</b>, no default: type a value in the table</span>")
                               .arg(name.toHtmlEscaped()));
        }
        missingLay_->addWidget(row);
    }
    missingBox_->setVisible(!missing.empty());
}

void EntityInspector::refreshLightGroup(const Entity* e) {
    const std::string cls = e->classname();
    const bool light = cls == "light" || cls == "light_spot";
    lightGroup_->setVisible(light);
    if (!light) return;
    const QColor c = lightColorOf(e);
    lightColor_->setStyleSheet(QString("background-color: %1;").arg(c.name()));
    lightColor_->setText(QString("%1 %2 %3").arg(c.redF(), 0, 'f', 2).arg(c.greenF(), 0, 'f', 2).arg(c.blueF(), 0, 'f', 2));
    setQuietly(lightRadius_, numberOr(e->value("radius"), 400));
    setQuietly(lightFovOuter_, numberOr(e->value("fov_outer"), 90));
    setQuietly(lightFovInner_, numberOr(e->value("fov_inner"), 60));
}

void EntityInspector::refresh() {
    // Do not rebuild while a cell editor is open (it would destroy the mapper's in-progress text).
    if (QWidget* fw = QApplication::focusWidget(); fw && fw != table_ && table_->isAncestorOf(fw)) return;
    const Id eid = ctx_->doc.inspectedEntity();
    const Entity* e = ctx_->doc.findEntity(eid);
    filling_ = true;
    table_->setRowCount(0);
    if (!e) {
        shownEntity_ = kNoId;
        header_->setText("<i>No entity</i>");
        classInfo_->clear();
        showMissing({}, eid);
        lightGroup_->setVisible(false);
        filling_ = false;
        return;
    }
    size_t index = 0;
    for (size_t i = 0; i < ctx_->doc.map().entities.size(); ++i)
        if (ctx_->doc.map().entities[i].id == eid) index = i;
    QString h = QString("<b>%1</b> &nbsp; <span style='color:gray'>entity %2%3</span>")
                    .arg(qs(e->classname().empty() ? "(no classname)" : e->classname()).toHtmlEscaped())
                    .arg(index)
                    .arg(e->usesCanonicalKeys() ? " &middot; IW8 runtime keys (canonical ids)" : "");
    if (ctx_->doc.selection().empty()) h += "<br><span style='color:gray'>Nothing selected: showing worldspawn.</span>";
    header_->setText(h);
    const ClassDef* def = entityDefs().find(e->classname());
    for (const auto& it : e->items) {
        const KeyValueLine* kv = it.kv();
        if (!kv) continue;
        const int r = table_->rowCount();
        table_->insertRow(r);
        const KeyDef* kd = def ? def->key(kv->name()) : nullptr;
        auto* key = new QTableWidgetItem(qs(kv->name()));
        key->setFlags(key->flags() & ~Qt::ItemIsEditable);
        QStringList tip;
        if (kv->form == KeyForm::Canonical) tip << QString("canonical id %1").arg(kv->keyId);
        else if (kv->form == KeyForm::ScriptString) tip << "script-string key (0 name \"value\")";
        if (kd) tip << keyDocTooltip(*kd);
        key->setToolTip(tip.join("\n\n"));
        table_->setItem(r, 0, key);
        auto* value = new QTableWidgetItem(qs(kv->value));
        if (kd && !kv->value.empty()) {
            const QString problem = valueProblem(kd->type, kv->value);
            if (!problem.isEmpty()) {
                value->setBackground(invalidTint(table_->palette()));
                value->setToolTip(QString("Not a valid %1 for %2: expected %3.").arg(qs(kd->type), qs(kd->name), problem));
            }
        }
        table_->setItem(r, 1, value);
        if (kv->name() != "classname") {
            auto* del = new QToolButton(table_);
            del->setText(QString::fromUtf8("\xC3\x97"));
            del->setToolTip("Remove key");
            del->setAutoRaise(true);
            const QString name = qs(kv->name());
            connect(del, &QToolButton::clicked, this, [this, eid, name] {
                if (ctx_->doc.removeKey(eid, name.toStdString())) ctx_->documentEdited("Removed \"" + name + "\"");
            });
            table_->setCellWidget(r, 2, del);
        }
    }
    shownEntity_ = eid;
    filling_ = false;
    {
        // Class box, class description, missing required keys and key suggestions: the documented keys first, then the stock ones.
        const QString cls = qs(e->classname());
        const QSignalBlocker block(classBox_);
        classBox_->setEditText(cls);
        classBox_->setEnabled(!e->isWorldspawn());
        classInfo_->setText(classInfoHtml(def, *e));
        showMissing(def && !e->isWorldspawn() ? missingRequired(*def, *e) : std::vector<const KeyDef*>{}, eid);
        QStringList keys;
        if (def)
            for (const KeyDef& kd : def->keys)
                if (rowForKey(qs(kd.name)) < 0) keys << qs(kd.name);
        const QJsonObject stock = stockClasses().value(cls).toObject().value("keys").toObject();
        QList<QPair<int, QString>> sorted;
        for (auto it = stock.begin(); it != stock.end(); ++it) sorted.append({it.value().toObject().value("count").toInt(), it.key()});
        std::sort(sorted.begin(), sorted.end(), [](const auto& a, const auto& b) { return a.first > b.first; });
        for (const auto& [count, name] : sorted)
            if (rowForKey(name) < 0 && !keys.contains(name)) keys << name;
        keyModel_->setStringList(keys);
        newKey_->setToolTip(keys.isEmpty() ? QString() : "Stock keys for " + cls + ": " + keys.mid(0, 12).join(", "));
    }
    refreshLightGroup(e);

    // Selected primitives: IW8 material names per face/patch.
    size_t prims = 0;
    std::set<std::string> mats;
    for (const auto& r : ctx_->doc.selection()) {
        const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr;
        const Primitive* p = it ? it->prim() : nullptr;
        if (!p) continue;
        ++prims;
        if (p->kind == PrimKind::Patch) mats.insert(p->patchMaterial);
        for (const auto& f : p->faces) mats.insert(f.material());
    }
    if (!prims) {
        surfaces_->clear();
        return;
    }
    QString s = QString("<b>%1 primitive(s) selected</b> &mdash; materials:<br>").arg(prims);
    for (const auto& m : mats) s += "&bull; " + qs(m).toHtmlEscaped() + "<br>";
    const AABB b = ctx_->doc.selectionBounds();
    if (b.valid())
        s += QString("<span style='color:gray'>bounds %1 %2 %3 .. %4 %5 %6</span>")
                 .arg(qs(formatNumber(b.mins.x)), qs(formatNumber(b.mins.y)), qs(formatNumber(b.mins.z)), qs(formatNumber(b.maxs.x)),
                      qs(formatNumber(b.maxs.y)), qs(formatNumber(b.maxs.z)));
    surfaces_->setText(s);
}

