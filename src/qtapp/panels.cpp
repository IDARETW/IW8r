// The IW8 entity definitions (data/iw8_entity_defs.json, the table Check Map uses). Loaded once from the first data
// folder found walking up from the executable, as asset_browser.cpp does. Empty when the file is missing.
const EntityDefs& entityDefs() {
    static const EntityDefs defs = [] {
        EntityDefs d;
        QDir dir(QCoreApplication::applicationDirPath());
        for (int up = 0; up < 3; ++up, dir.cdUp()) {
            const QString path = dir.filePath("data/iw8_entity_defs.json");
            if (!QFileInfo::exists(path)) continue;
            std::string err;
            d.load(path.toStdString(), &err);
            break;
        }
        return d;
    }();
    return defs;
}

double clamp01(double v) { return std::clamp(v, 0.0, 1.0); }

// The numbers in a value, or an empty list when any token is not a finite number.
std::vector<double> numbersOf(const std::string* v) {
    std::vector<double> out;
    if (!v) return out;
    for (const QString& t : qs(*v).simplified().split(' ', Qt::SkipEmptyParts)) {
        bool ok = false;
        const double d = t.toDouble(&ok);
        if (!ok || !std::isfinite(d)) return {};
        out.push_back(d);
    }
    return out;
}

double numberOr(const std::string* v, double def) {
    const std::vector<double> n = numbersOf(v);
    return n.size() == 1 ? n[0] : def;
}

// _color as the compiler reads it: 0..1 floats, or 0..255 when any component is above 1 (compile_iw8.cpp).
QColor lightColorOf(const Entity* e) {
    const std::vector<double> c = numbersOf(e ? e->value("_color") : nullptr);
    if (c.size() != 3) return QColor(255, 255, 255);
    const double s = std::max({c[0], c[1], c[2]}) > 1.0 ? 1.0 / 255.0 : 1.0;
    return QColor::fromRgbF(clamp01(c[0] * s), clamp01(c[1] * s), clamp01(c[2] * s));
}

// Empty when `value` fits `type`; otherwise what it should look like. The same rules as EntityDefs::validate.
QString valueProblem(const std::string& type, const std::string& value) {
    const QStringList tok = qs(value).simplified().split(' ', Qt::SkipEmptyParts);
    auto isNumber = [](const QString& s) {
        bool ok = false;
        const double d = s.toDouble(&ok);
        return ok && std::isfinite(d);
    };
    if (type == "int") {
        bool ok = false;
        if (tok.size() == 1) tok[0].toLongLong(&ok);
        return ok ? QString() : QString("an integer");
    }
    if (type == "float") return (tok.size() == 1 && isNumber(tok[0])) ? QString() : QString("a number");
    if (type == "vec3" || type == "angles") {
        bool ok = tok.size() == 3;
        for (const QString& t : tok) ok = ok && isNumber(t);
        return ok ? QString() : QString("three numbers");
    }
    if (type == "bool") {
        const QString v = tok.size() == 1 ? tok[0].toLower() : QString();
        return (v == "0" || v == "1" || v == "true" || v == "false") ? QString() : QString("0, 1, true or false");
    }
    return QString();
}

QString keyDocTooltip(const KeyDef& k) {
    QString t = QString("%1 (%2)").arg(qs(k.name), qs(k.type));
    t += "\ndefault: " + (k.defaultValue.empty() ? QString("none") : qs(k.defaultValue));
    if (k.required) t += "\nrequired";
    if (!k.description.empty()) t += "\n" + qs(k.description);
    if (!k.examples.empty()) {
        QStringList ex;
        for (size_t i = 0; i < k.examples.size() && i < 4; ++i) ex << qs(k.examples[i]);
        t += "\nexamples: " + ex.join(", ");
    }
    return t;
}

// The value a missing required key is added with: its documented default, else a zero of its type.
std::optional<std::string> defaultFor(const KeyDef& k) {
    if (!k.defaultValue.empty()) return k.defaultValue;
    if (k.type == "vec3" || k.type == "angles") return std::string("0 0 0");
    if (k.type == "int" || k.type == "float" || k.type == "bool") return std::string("0");
    return std::nullopt;
}

std::vector<const KeyDef*> missingRequired(const ClassDef& def, const Entity& e) {
    std::vector<const KeyDef*> out;
    for (const KeyDef& k : def.keys) {
        if (!k.required) continue;
        const std::string* v = e.value(k.name);
        if (!v || v->empty()) out.push_back(&k);
    }
    return out;
}

QString classInfoHtml(const ClassDef* def, const Entity& e) {
    if (!def)
        return e.isWorldspawn() ? QString() : QString("<span style='color:gray'>No IW8 entity definition; built into Replay: no.</span>");
    return QString("%1<br><span style='color:gray'>built into Replay: %2</span>")
        .arg(qs(def->description).toHtmlEscaped(), QString(def->buildAccepted ? "yes" : "no"));
}

void setQuietly(QDoubleSpinBox* spin, double v) {
    const QSignalBlocker block(spin);
    spin->setValue(v);
}

// Red tint for a value that does not fit its key type, dark enough or light enough for the palette.
QColor invalidTint(const QPalette& pal) { return pal.color(QPalette::Window).lightness() < 128 ? QColor(110, 30, 30) : QColor(255, 200, 200); }

