HotkeysPanel::HotkeysPanel(const QMap<QString, QAction*>& actions, QWidget* parent) : QWidget(parent) {
    auto* lay = new QVBoxLayout(this);
    lay->setContentsMargins(4, 4, 4, 4);
    auto* note = new QLabel("Click a shortcut to rebind it. Defaults follow the stock CoD Radiant table; bindings are saved to IW8Radiant.ini.", this);
    note->setWordWrap(true);
    lay->addWidget(note);
    table_ = new QTableWidget(0, 2, this);
    table_->setHorizontalHeaderLabels({"Command", "Shortcut"});
    table_->horizontalHeader()->setSectionResizeMode(0, QHeaderView::Stretch);
    table_->horizontalHeader()->setSectionResizeMode(1, QHeaderView::Stretch);
    table_->verticalHeader()->setVisible(false);
    lay->addWidget(table_, 1);
    for (auto it = actions.begin(); it != actions.end(); ++it) {
        const int r = table_->rowCount();
        table_->insertRow(r);
        auto* name = new QTableWidgetItem(it.key());
        name->setFlags(name->flags() & ~Qt::ItemIsEditable);
        name->setToolTip(it.value()->text().remove('&'));
        table_->setItem(r, 0, name);
        auto* edit = new QKeySequenceEdit(it.value()->shortcut(), table_);
        QAction* action = it.value();
        const QString command = it.key();
        connect(edit, &QKeySequenceEdit::editingFinished, this, [this, action, edit, command, actions] {
            // A key another command has: ask, and take it from that command (two commands on one key both stop working).
            const QKeySequence seq = edit->keySequence();
            if (!seq.isEmpty())
                for (auto o = actions.begin(); o != actions.end(); ++o) {
                    if (o.value() == action || o.value()->shortcut() != seq) continue;
                    if (QMessageBox::question(this, "Hotkeys",
                                              QString("%1 is already the key of %2.\n\nUse it for %3 instead (%2 is left without a key)?")
                                                  .arg(seq.toString(QKeySequence::NativeText), o.value()->text().remove('&'), action->text().remove('&'))) !=
                        QMessageBox::Yes) {
                        const QSignalBlocker block(edit);
                        edit->setKeySequence(action->shortcut());
                        return;
                    }
                    o.value()->setShortcut(QKeySequence());
                    Settings::instance().setShortcut(o.key(), QKeySequence());
                    for (int r = 0; r < table_->rowCount(); ++r)
                        if (table_->item(r, 0) && table_->item(r, 0)->text() == o.key())
                            if (auto* other = qobject_cast<QKeySequenceEdit*>(table_->cellWidget(r, 1))) {
                                const QSignalBlocker block(other);
                                other->clear();
                            }
                }
            action->setShortcut(seq);
            Settings::instance().setShortcut(command, seq);
        });
        table_->setCellWidget(r, 1, edit);
    }
    const char* camera[][2] = {{"Camera forward / back", "Up / Down"}, {"Camera turn", "Left / Right"}, {"Camera strafe", "Comma / Period"},
                               {"Camera up / down", "D / C"}, {"Camera pitch", "A / Z"}, {"Mouse look", "RMB drag (+ W/A/S/D/Q/E fly)"},
                               {"Move forward + yaw", "Ctrl+RMB drag"}, {"Select in camera", "LMB click, Shift+LMB toggle"},
                               {"Select in grid", "Shift+LMB"}, {"Move selection in grid", "LMB drag inside the selection"},
                               {"Pan / zoom grid", "RMB or MMB drag / wheel"}};
    for (const auto& c : camera) {
        const int r = table_->rowCount();
        table_->insertRow(r);
        auto* a = new QTableWidgetItem(c[0]);
        auto* b = new QTableWidgetItem(c[1]);
        a->setFlags(Qt::ItemIsEnabled);
        b->setFlags(Qt::ItemIsEnabled);
        a->setForeground(QColor(140, 140, 140));
        b->setForeground(QColor(140, 140, 140));
        table_->setItem(r, 0, a);
        table_->setItem(r, 1, b);
    }
}

