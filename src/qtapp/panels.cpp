EntityInspector::EntityInspector(EditorContext* ctx, QWidget* parent) : QWidget(parent), ctx_(ctx) {
    auto* lay = new QVBoxLayout(this);
    lay->setContentsMargins(6, 6, 6, 6);
    header_ = new QLabel(this);
    header_->setTextFormat(Qt::RichText);
    header_->setWordWrap(true);
    lay->addWidget(header_);
    auto* classRow = new QHBoxLayout();
    classRow->addWidget(new QLabel("Class", this));
    classBox_ = new QComboBox(this);
    classBox_->setObjectName("classBox");
    classBox_->setEditable(true);
    classBox_->setInsertPolicy(QComboBox::NoInsert);
    {
        // Most common stock classes first; the tooltip says where each was seen.
        QList<QPair<int, QString>> sorted;
        for (auto it = stockClasses().begin(); it != stockClasses().end(); ++it)
            sorted.append({it.value().toObject().value("count").toInt(), it.key()});
        std::sort(sorted.begin(), sorted.end(), [](const auto& a, const auto& b) { return a.first > b.first; });
        for (const auto& [count, name] : sorted) {
            classBox_->addItem(name);
            const auto maps = stockClasses().value(name).toObject().value("maps").toArray();
            QStringList m;
            for (const auto& v : maps) m << v.toString();
            classBox_->setItemData(classBox_->count() - 1, QString("%1 in stock %2").arg(count).arg(m.join(", ")), Qt::ToolTipRole);
        }
        classBox_->completer()->setFilterMode(Qt::MatchContains);
        classBox_->completer()->setCaseSensitivity(Qt::CaseInsensitive);
    }
    classRow->addWidget(classBox_, 1);
    lay->addLayout(classRow);
    connect(classBox_->lineEdit(), &QLineEdit::editingFinished, this, [this] {
        const QString cls = classBox_->currentText().trimmed();
        const Id e = ctx_->doc.inspectedEntity();
        const Entity* ent = ctx_->doc.findEntity(e);
        if (!ent || cls.isEmpty() || ent->isWorldspawn() || qs(ent->classname()) == cls) return;
        if (ctx_->doc.setKeyValue(e, "classname", cls.toStdString())) ctx_->documentEdited("Set classname " + cls);
    });
    // IW8 definition of the class: description and whether the build accepts it.
    classInfo_ = new QLabel(this);
    classInfo_->setObjectName("classInfo");
    classInfo_->setTextFormat(Qt::RichText);
    classInfo_->setWordWrap(true);
    classInfo_->setTextInteractionFlags(Qt::TextSelectableByMouse);
    lay->addWidget(classInfo_);
    // Warning line for required keys that are missing, each with an Add button.
    missingBox_ = new QWidget(this);
    missingBox_->setObjectName("missingBox");
    missingLay_ = new QVBoxLayout(missingBox_);
    missingLay_->setContentsMargins(0, 0, 0, 0);
    missingBox_->setVisible(false);
    lay->addWidget(missingBox_);
    // Light group: writes _color (0..1 floats), radius, fov_outer and fov_inner (the keys the compiler reads).
    lightGroup_ = new QGroupBox("Light", this);
    lightGroup_->setObjectName("lightGroup");
    lightGroup_->setVisible(false);
    auto* lightLay = new QGridLayout(lightGroup_);
    lightColor_ = new QPushButton(lightGroup_);
    lightColor_->setObjectName("lightColor");
    lightColor_->setToolTip("Pick the light colour. Written to _color as 0..1 floats.");
    lightLay->addWidget(new QLabel("Colour", lightGroup_), 0, 0);
    lightLay->addWidget(lightColor_, 0, 1);
    auto lightSpin = [this, lightLay](int row, const char* label, std::string key, const char* objName, double hi, double def,
                                      const char* tip) {
        auto* spin = new QDoubleSpinBox(lightGroup_);
        spin->setObjectName(objName);
        spin->setRange(1, hi);
        spin->setDecimals(1);
        spin->setValue(def);
        spin->setKeyboardTracking(false);
        spin->setToolTip(tip);
        lightLay->addWidget(new QLabel(label, lightGroup_), row, 0);
        lightLay->addWidget(spin, row, 1);
        connect(spin, &QDoubleSpinBox::valueChanged, this, [this, key](double v) {
            const Id e = ctx_->doc.inspectedEntity();
            if (ctx_->doc.setKeyValue(e, key, formatNumber(v))) ctx_->documentEdited(QString("Set \"%1\"").arg(qs(key)));
        });
        return spin;
    };
    lightRadius_ = lightSpin(1, "Radius", "radius", "lightRadius", 100000, 400, "Light radius (radius). The compiler default is 400.");
    lightFovOuter_ = lightSpin(2, "FOV outer", "fov_outer", "lightFovOuter", 170, 90,
                               "Outer cone angle in degrees (fov_outer, 1..170). Spot lights.");
    lightFovInner_ = lightSpin(3, "FOV inner", "fov_inner", "lightFovInner", 170, 60,
                               "Inner cone angle in degrees (fov_inner, 1..170). Spot lights.");
    lay->addWidget(lightGroup_);
    connect(lightColor_, &QPushButton::clicked, this, [this] {
        const QColor cur = lightColorOf(ctx_->doc.findEntity(ctx_->doc.inspectedEntity()));
        const QColor c = QColorDialog::getColor(cur, this, "Light colour");
        if (c.isValid()) setLightColor(c.redF(), c.greenF(), c.blueF());
    });
    table_ = new QTableWidget(0, 3, this);
    table_->setObjectName("kvTable");
    table_->setHorizontalHeaderLabels({"Key", "Value", ""});
    table_->horizontalHeader()->setSectionResizeMode(0, QHeaderView::Interactive);
    table_->horizontalHeader()->setSectionResizeMode(1, QHeaderView::Stretch);
    table_->horizontalHeader()->setSectionResizeMode(2, QHeaderView::Fixed);
    table_->setColumnWidth(0, 150);
    table_->setColumnWidth(2, 28);
    table_->verticalHeader()->setVisible(false);
    table_->setEditTriggers(QAbstractItemView::DoubleClicked | QAbstractItemView::EditKeyPressed | QAbstractItemView::AnyKeyPressed);
    table_->setAlternatingRowColors(true);
    lay->addWidget(table_, 1);
    auto* addRow = new QHBoxLayout();
    newKey_ = new QLineEdit(this);
    newKey_->setObjectName("newKey");
    newKey_->setPlaceholderText("key (stock keys for this class are suggested)");
    keyModel_ = new QStringListModel(this);
    auto* keyCompleter = new QCompleter(keyModel_, this);
    keyCompleter->setCaseSensitivity(Qt::CaseInsensitive);
    keyCompleter->setFilterMode(Qt::MatchContains);
    newKey_->setCompleter(keyCompleter);
    newValue_ = new QLineEdit(this);
    newValue_->setObjectName("newValue");
    newValue_->setPlaceholderText("value");
    auto* add = new QPushButton("Add", this);
    addRow->addWidget(newKey_, 1);
    addRow->addWidget(newValue_, 2);
    addRow->addWidget(add);
    lay->addLayout(addRow);
    surfaces_ = new QLabel(this);
    surfaces_->setWordWrap(true);
    surfaces_->setTextInteractionFlags(Qt::TextSelectableByMouse);
    lay->addWidget(surfaces_);

    auto addKey = [this] {
        const QString k = newKey_->text().trimmed();
        if (k.isEmpty()) return;
        // The key goes on the entity the table shows, and only when the value fits the key's documented type: the
        // fields keep the text so the mapper can correct it.
        if (const QString why = refusalFor(k, newValue_->text()); !why.isEmpty()) {
            ctx_->setStatus("Not added: " + why);
            newValue_->setFocus();
            newValue_->selectAll();
            return;
        }
        if (ctx_->doc.setKeyValue(shownEntity_, k.toStdString(), newValue_->text().toStdString())) {
            newKey_->clear();
            newValue_->clear();
            ctx_->documentEdited("Set \"" + k + "\"");
        }
    };
    connect(add, &QPushButton::clicked, this, addKey);
    connect(newValue_, &QLineEdit::returnPressed, this, addKey);
    // Enter in the key name goes on to its value, as Tab does.
    connect(newKey_, &QLineEdit::returnPressed, this, [this] {
        newValue_->setFocus();
        newValue_->selectAll();
    });
    connect(table_, &QTableWidget::cellChanged, this, &EntityInspector::commitCell);
    table_->installEventFilter(this);  // Delete removes the keys of the selected rows
    connect(ctx_, &EditorContext::documentChanged, this, &EntityInspector::refresh);
    refresh();
}

