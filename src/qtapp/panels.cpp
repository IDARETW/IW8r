SurfacePanel::SurfacePanel(EditorContext* ctx, QWidget* parent) : QWidget(parent), ctx_(ctx) {
    auto* lay = new QVBoxLayout(this);
    lay->setContentsMargins(6, 6, 6, 6);
    info_ = new QLabel(this);
    info_->setWordWrap(true);
    lay->addWidget(info_);
    auto* grid = new QGridLayout();
    const char* names[5] = {"Texture width", "Texture height", "Offset X", "Offset Y", "Rotation"};
    const double steps[5] = {8, 8, 1, 1, 15};
    for (int i = 0; i < 5; ++i) {
        auto* spin = new QDoubleSpinBox(this);
        spin->setObjectName(QString("surface%1").arg(i));
        spin->setRange(i == 4 ? -360 : -65536, i == 4 ? 360 : 65536);
        spin->setDecimals(3);
        spin->setSingleStep(steps[i]);
        spin->setKeyboardTracking(false);
        fields_[i] = spin;
        grid->addWidget(new QLabel(names[i], this), i, 0);
        grid->addWidget(spin, i, 1);
        auto* minus = new QToolButton(this);
        auto* plus = new QToolButton(this);
        const bool scale = i < 2;
        minus->setObjectName(QString("surfaceMinus%1").arg(i));
        plus->setObjectName(QString("surfacePlus%1").arg(i));
        minus->setText(scale ? QString::fromUtf8("\xC3\xB7" "2") : "-");
        plus->setText(scale ? QString::fromUtf8("\xC3\x97" "2") : "+");
        grid->addWidget(minus, i, 2);
        grid->addWidget(plus, i, 3);
        connect(minus, &QToolButton::clicked, this, [this, i, scale] { nudge(i, scale ? 0.5 : -(i < 4 ? ctx_->doc.grid() : 15.0), scale); });
        connect(plus, &QToolButton::clicked, this, [this, i, scale] { nudge(i, scale ? 2.0 : (i < 4 ? ctx_->doc.grid() : 15.0), scale); });
        connect(spin, &QDoubleSpinBox::valueChanged, this, [this, i](double v) {
            if (filling_) return;
            Primitive::TexFields f;
            std::optional<double>* slot[5] = {&f.width, &f.height, &f.xoff, &f.yoff, &f.rot};
            *slot[i] = v;
            apply(f, "Surface");
        });
    }
    {
        // Lightmap scale (the lightmap token pair after the texture fields; 16384 = the stock default).
        const char* lmNames[2] = {"Lightmap scale X", "Lightmap scale Y"};
        for (int i = 0; i < 2; ++i) {
            auto* spin = new QDoubleSpinBox(this);
            spin->setObjectName(QString("surfaceLightmap%1").arg(i));
            spin->setRange(1, 1048576);
            spin->setDecimals(1);
            spin->setSingleStep(1024);
            spin->setKeyboardTracking(false);
            spin->setToolTip("Lightmap scale written to the face's lightmap tokens (L1 / L2); other lightmap tokens are kept");
            lmFields_[i] = spin;
            grid->addWidget(new QLabel(lmNames[i], this), 5 + i, 0);
            grid->addWidget(spin, 5 + i, 1);
            connect(spin, &QDoubleSpinBox::valueChanged, this, [this](double) {
                if (filling_) return;
                if (applyLightmapScale(lmFields_[0]->value(), lmFields_[1]->value())) ctx_->documentEdited("Lightmap scale");
            });
        }
    }
    lay->addLayout(grid);
    {
        auto* row = new QHBoxLayout();
        const std::pair<const char*, Op> ops[] = {{"Fit", Op::Fit},          {"Natural", Op::Natural},     {"Left", Op::JustifyLeft},
                                                  {"Right", Op::JustifyRight}, {"Top", Op::JustifyTop}, {"Bottom", Op::JustifyBottom},
                                                  {"Center", Op::JustifyCenter}};
        for (const auto& [label, op] : ops) {
            auto* b = new QToolButton(this);
            b->setText(label);
            b->setObjectName(QString("surfaceOp%1").arg(label));
            connect(b, &QToolButton::clicked, this, [this, op = op] { applyOp(op); });
            row->addWidget(b);
        }
        row->addStretch(1);
        lay->addLayout(row);
    }
    lay->addStretch(1);
    connect(ctx_, &EditorContext::documentChanged, this, &SurfacePanel::refresh);
    refresh();
}

void SurfacePanel::apply(const Primitive::TexFields& f, const QString& what) {
    std::vector<Document::PrimEdit> edits;
    if (!ctx_->doc.faceSelection().empty()) {
        std::map<std::pair<Id, Id>, Primitive> work;
        for (const FaceRef& fr : ctx_->doc.faceSelection()) {
            const EntityItem* it = ctx_->doc.findItem(fr.entity, fr.item);
            if (!it || !it->prim()) continue;
            auto w = work.find({fr.entity, fr.item});
            if (w == work.end()) w = work.emplace(std::make_pair(fr.entity, fr.item), *it->prim()).first;
            w->second.setTextureFields(f, int(fr.face));
        }
        for (auto& [key, p] : work) edits.push_back({key.first, key.second, p});
        if (ctx_->doc.editPrimitives(edits, what.toStdString(), false)) ctx_->documentEdited(what + " (faces, undoable)");
        return;
    }
    for (const auto& r : ctx_->doc.selection()) {
        const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr;
        if (!it || !it->prim() || it->prim()->kind != PrimKind::Brush) continue;
        Primitive p = *it->prim();
        if (p.setTextureFields(f)) edits.push_back({r.entity, r.item, p});
    }
    if (ctx_->doc.editPrimitives(edits, what.toStdString())) ctx_->documentEdited(what + " (undoable)");
}

void SurfacePanel::nudge(int field, double delta, bool multiply) {
    // Per face: offsets/rotation add, width/height multiply; one undo step for the whole selection.
    std::vector<Document::PrimEdit> edits;
    if (!ctx_->doc.faceSelection().empty()) {
        std::map<std::pair<Id, Id>, Primitive> work;
        for (const FaceRef& fr : ctx_->doc.faceSelection()) {
            const EntityItem* it = ctx_->doc.findItem(fr.entity, fr.item);
            if (!it || !it->prim()) continue;
            auto w = work.find({fr.entity, fr.item});
            if (w == work.end()) w = work.emplace(std::make_pair(fr.entity, fr.item), *it->prim()).first;
            auto cur = w->second.textureFields(fr.face);
            if (!cur) continue;
            Primitive::TexFields tf;
            std::optional<double>* slot[5] = {&tf.width, &tf.height, &tf.xoff, &tf.yoff, &tf.rot};
            const double v = (*cur)[size_t(field)];
            *slot[field] = multiply ? v * delta : v + delta;
            w->second.setTextureFields(tf, int(fr.face));
        }
        for (auto& [key, p] : work) edits.push_back({key.first, key.second, p});
        if (ctx_->doc.editPrimitives(edits, "Surface", false)) ctx_->documentEdited("Surface (faces, undoable)");
        return;
    }
    for (const auto& r : ctx_->doc.selection()) {
        const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr;
        if (!it || !it->prim() || it->prim()->kind != PrimKind::Brush) continue;
        Primitive p = *it->prim();
        bool changed = false;
        for (size_t fi = 0; fi < p.faces.size(); ++fi) {
            auto cur = p.textureFields(fi);
            if (!cur) continue;
            Primitive::TexFields f;
            std::optional<double>* slot[5] = {&f.width, &f.height, &f.xoff, &f.yoff, &f.rot};
            const double v = (*cur)[size_t(field)];
            *slot[field] = multiply ? v * delta : v + delta;
            changed |= p.setTextureFields(f, int(fi));
        }
        if (changed) edits.push_back({r.entity, r.item, p});
    }
    if (ctx_->doc.editPrimitives(edits, "Surface")) ctx_->documentEdited("Surface (undoable)");
}

bool SurfacePanel::applyOp(Op op) {
    // Targets: selected faces, else every face of the selected brushes.
    std::map<std::pair<Id, Id>, std::pair<Primitive, std::vector<size_t>>> work;
    auto add = [&](Id e, Id i, size_t face) {
        const EntityItem* it = ctx_->doc.findItem(e, i);
        if (!it || !it->prim() || it->prim()->kind != PrimKind::Brush) return;
        auto w = work.find({e, i});
        if (w == work.end()) w = work.emplace(std::make_pair(e, i), std::make_pair(*it->prim(), std::vector<size_t>{})).first;
        w->second.second.push_back(face);
    };
    const bool faces = !ctx_->doc.faceSelection().empty();
    if (faces)
        for (const FaceRef& f : ctx_->doc.faceSelection()) add(f.entity, f.item, f.face);
    else
        for (const auto& r : ctx_->doc.selection())
            if (const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr; it && it->prim())
                for (size_t f = 0; f < it->prim()->faces.size(); ++f) add(r.entity, r.item, f);
    std::vector<Document::PrimEdit> edits;
    for (auto& [key, pw] : work) {
        Primitive& p = pw.first;
        const Primitive original = p;
        const auto wins = faceWindingsOf(original);
        for (size_t f : pw.second) {
            const auto tp = texParamsOfFace(original, f);
            const auto pl = facePlane(original, f);
            if (!tp || !pl || f >= wins.size() || wins[f].size() < 3) continue;
            TexParams out = *tp;
            switch (op) {
                case Op::Fit: out = fitTexture(pl->n, *tp, wins[f]); break;
                case Op::Natural: out = naturalTexture(*tp); break;
                case Op::JustifyLeft: out = justifyTexture(pl->n, *tp, wins[f], Justify::Left); break;
                case Op::JustifyRight: out = justifyTexture(pl->n, *tp, wins[f], Justify::Right); break;
                case Op::JustifyTop: out = justifyTexture(pl->n, *tp, wins[f], Justify::Top); break;
                case Op::JustifyBottom: out = justifyTexture(pl->n, *tp, wins[f], Justify::Bottom); break;
                case Op::JustifyCenter: out = justifyTexture(pl->n, *tp, wins[f], Justify::Center); break;
            }
            applyTexParams(p, f, out);
        }
        if (p.text() != original.text()) edits.push_back({key.first, key.second, p});
    }
    const char* names[] = {"Fit Texture", "Natural Texture", "Justify Left", "Justify Right", "Justify Top", "Justify Bottom", "Justify Center"};
    if (!ctx_->doc.editPrimitives(edits, names[int(op)], !faces)) return false;
    ctx_->documentEdited(QString(names[int(op)]) + " (undoable)");
    return true;
}

bool SurfacePanel::applyLightmapScale(double sx, double sy) {
    auto withScale = [&](LightmapParams lp) {
        lp.sx = sx, lp.sy = sy;
        return lp;
    };
    if (!ctx_->doc.faceSelection().empty()) {
        const FaceRef& fr = *ctx_->doc.faceSelection().begin();
        const EntityItem* it = ctx_->doc.findItem(fr.entity, fr.item);
        const auto cur = it && it->prim() ? lightmapParamsOfFace(*it->prim(), fr.face) : std::nullopt;
        return setLightmapOnSelection(ctx_->doc, withScale(cur.value_or(LightmapParams{})));
    }
    std::vector<Document::PrimEdit> edits;
    for (const auto& r : ctx_->doc.selection()) {
        const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr;
        const Primitive* p = it ? it->prim() : nullptr;
        if (!p || p->kind != PrimKind::Brush) continue;
        const auto cur = lightmapParamsOfFace(*p, 0);
        if (auto np = withLightmapParams(*p, kAllFaces, withScale(cur.value_or(LightmapParams{}))); np && np->text() != p->text())
            edits.push_back({r.entity, r.item, *np});
    }
    return !edits.empty() && ctx_->doc.editPrimitives(edits, "Lightmap Scale");
}

void SurfacePanel::refresh() {
    {
        // Lightmap scale of the first selected face, else the first face of the first selected brush.
        std::optional<LightmapParams> lp;
        if (!ctx_->doc.faceSelection().empty()) {
            const FaceRef& fr = *ctx_->doc.faceSelection().begin();
            const EntityItem* it = ctx_->doc.findItem(fr.entity, fr.item);
            if (it && it->prim()) lp = lightmapParamsOfFace(*it->prim(), fr.face);
        } else {
            for (const auto& r : ctx_->doc.selection()) {
                const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr;
                if (it && it->prim() && it->prim()->kind == PrimKind::Brush) {
                    lp = lightmapParamsOfFace(*it->prim(), 0);
                    break;
                }
            }
        }
        filling_ = true;
        for (int i = 0; i < 2; ++i) {
            lmFields_[i]->setEnabled(lp.has_value());
            if (lp) lmFields_[i]->setValue(i == 0 ? lp->sx : lp->sy);
        }
        filling_ = false;
    }
    if (!ctx_->doc.faceSelection().empty()) {
        const FaceRef& fr = *ctx_->doc.faceSelection().begin();
        const EntityItem* it = ctx_->doc.findItem(fr.entity, fr.item);
        const Primitive* p = it ? it->prim() : nullptr;
        const auto vals = p ? p->textureFields(fr.face) : std::nullopt;
        filling_ = true;
        for (int i = 0; i < 5; ++i) {
            fields_[i]->setEnabled(vals.has_value());
            if (vals) fields_[i]->setValue((*vals)[size_t(i)]);
        }
        filling_ = false;
        info_->setText(QString("%1 face(s); material <b>%2</b>. Fields show the first face; edits apply to the selected faces.")
                           .arg(ctx_->doc.faceSelection().size())
                           .arg(qs(p && fr.face < p->faces.size() ? p->faces[fr.face].material() : std::string()).toHtmlEscaped()));
        return;
    }
    const Primitive* first = nullptr;
    size_t brushes = 0;
    for (const auto& r : ctx_->doc.selection()) {
        const EntityItem* it = r.item ? ctx_->doc.findItem(r.entity, r.item) : nullptr;
        if (!it || !it->prim() || it->prim()->kind != PrimKind::Brush) continue;
        if (!first) first = it->prim();
        ++brushes;
    }
    filling_ = true;
    const auto vals = first ? first->textureFields(0) : std::nullopt;
    for (int i = 0; i < 5; ++i) {
        fields_[i]->setEnabled(vals.has_value());
        if (vals) fields_[i]->setValue((*vals)[size_t(i)]);
    }
    filling_ = false;
    info_->setText(first ? QString("%1 brush(es); material <b>%2</b>. Fields show the first face; edits apply to every face.")
                               .arg(brushes)
                               .arg(qs(first->faces.empty() ? std::string() : first->faces.front().material()).toHtmlEscaped())
                         : QString("Select brushes to edit their texture fields."));
}

// ------------------------------------------------------------------ history

HistoryPanel::HistoryPanel(EditorContext* ctx, QWidget* parent) : QWidget(parent), ctx_(ctx) {
    auto* lay = new QVBoxLayout(this);
    lay->setContentsMargins(4, 4, 4, 4);
    list_ = new QListWidget(this);
    lay->addWidget(list_);
    connect(list_, &QListWidget::currentRowChanged, this, [this](int row) {
        if (filling_ || row < 0) return;
        const size_t target = size_t(row);
        while (ctx_->doc.undoPosition() > target && ctx_->doc.undo()) {}
        while (ctx_->doc.undoPosition() < target && ctx_->doc.redo()) {}
        ctx_->documentEdited();
    });
    connect(ctx_, &EditorContext::documentChanged, this, &HistoryPanel::refresh);
    refresh();
}

void HistoryPanel::refresh() {
    filling_ = true;
    list_->clear();
    list_->addItem("(opened document)");
    const auto& h = ctx_->doc.history();
    const size_t pos = ctx_->doc.undoPosition();
    for (size_t i = 0; i < h.size(); ++i) {
        auto* item = new QListWidgetItem(qs(h[i].name));
        if (i >= pos) item->setForeground(QColor(120, 120, 120));
        list_->addItem(item);
    }
    list_->setCurrentRow(int(pos));
    filling_ = false;
}

