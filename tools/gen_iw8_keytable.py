"""Generate the IW8 canonical key table (id<TAB>name) used by IW8 Radiant Suite.

IW8 runtime entity strings (MapEnts::entityString, Replay 1.20.4.7623265) spell keys as
canonical script-string ids, e.g. `212 "worldspawn"`. The id -> name list is not shipped
with the editor; this script derives it on the mapper's machine from a local gsc-tool
checkout (src/gsc/engine/iw8_token.cpp, GPLv3, not redistributed here).

Only ids up to Replay 1.20's last compiled-in canonical string id (0xE2C0, per
x64-zt src/games/iw8/assets/gsc_tool_iw8_tokens.inc) are written, because larger ids are
not canonical in that build.

Usage:
    python -I tools/gen_iw8_keytable.py <path to iw8_token.cpp> [-o data/generated/iw8_canonical_keys.tsv]
"""
import argparse
import hashlib
import os
import re
import sys

REPLAY_120_LAST_CANONICAL = 0xE2C0
ROW = re.compile(r'\{\s*0x([0-9A-Fa-f]+)\s*,\s*"([^"]*)"\s*\}')
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("token_cpp")
    ap.add_argument("-o", "--output", default=os.path.join("data", "generated", "iw8_canonical_keys.tsv"))
    args = ap.parse_args()
    with open(args.token_cpp, "rb") as f:
        raw = f.read()
    text = raw.decode("utf-8", errors="replace")
    rows = []
    for m in ROW.finditer(text):
        ident, name = int(m.group(1), 16), m.group(2)
        if 0 < ident <= REPLAY_120_LAST_CANONICAL and IDENT.match(name):
            rows.append((ident, name))
    if not rows:
        print("error: no {0xID, \"name\"} rows found", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as out:
        out.write("# IW8 Replay 1.20 canonical key ids. Generated by tools/gen_iw8_keytable.py\n")
        out.write(f"# source: {os.path.abspath(args.token_cpp)}\n")
        out.write(f"# source sha256: {hashlib.sha256(raw).hexdigest()}\n")
        for ident, name in rows:
            out.write(f"{ident}\t{name}\n")
    print(f"wrote {len(rows)} keys to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
