"""Writes data/asset_catalog/iw8_br_loot_items.tsv: the item rows of every loot item table (mp/loot_item_defs*.csv of
code_post_gfx) - the brloot_* scriptables the Warzone loot system spawns on loot points. A custom map never loads
common_br_mp (docs/research/93), so the build carries the items of the map's loot table from that zone.

Input (read only): an ACTS stringtable export of code_post_gfx, default
out/warzone_study/code_post_gfx/mw19replay/code_post_gfx/assets/stringtable/mp/loot_item_defs*.csv.*.csv

Usage: py -3 -I tools/build_br_loot_items.py [export folder]"""
import csv, glob, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'out', 'warzone_study', 'code_post_gfx', 'mw19replay',
                                                           'code_post_gfx', 'assets', 'stringtable', 'mp')
dest = os.path.join(root, 'data', 'asset_catalog', 'iw8_br_loot_items.tsv')
rows = []
for path in sorted(glob.glob(os.path.join(src, 'loot_item_defs*.csv.*.csv'))):
    table = 'mp/' + re.sub(r'\.\d+\.csv$', '', os.path.basename(path))
    seen = set()
    with open(path, encoding='utf-8', newline='') as f:
        for row in csv.reader(f):
            if len(row) > 1 and row[0] == 'item' and row[1] and row[1] not in seen:
                seen.add(row[1])
                rows.append((table, row[1]))
if not rows:
    sys.exit('no loot item tables found under ' + src)
with open(dest, 'w', encoding='utf-8', newline='\n') as out:
    out.write('# Item rows of the Warzone loot item tables (code_post_gfx mp/loot_item_defs*.csv, Replay 1.20).\n')
    out.write('# Generated by tools/build_br_loot_items.py; do not edit. table<TAB>scriptable\n')
    for table, item in rows:
        out.write('%s\t%s\n' % (table, item))
print('wrote %s: %d rows from %d tables' % (dest, len(rows), len({t for t, _ in rows})))
