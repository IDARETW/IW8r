"""Writes data/generated/iw8_stock_scripts.tsv: the stock GSC files of the always-loaded zones and how each is named in
its zone, for the far-call check of the build preflight (docs/research/92).

The engine links a far call by the exact asset name: gsc-tool writes a path that has a token id as that number, and a
stock file stored under the same number links; a stock file stored under its path string is linked by string, but its
functions must then be named in the same form (research 92: br_gametypes::disablefeature cannot link).

Inputs (read only):
  ACTS scriptfile exports of common_base_mp and global_mp under out/warzone_study/<zone>/.../assets/scriptfile
  gsc-tool's IW8 token table (E:/mw124/acts-perf/deps/gsc-tool/src/gsc/engine/iw8_token.cpp) for the number -> path
Output rows: path<TAB>numbered|named<TAB>number (0 for named)<TAB>zone

Usage: py -3 -I tools/build_stock_script_index.py [token table]"""
import glob, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
token_file = sys.argv[1] if len(sys.argv) > 1 else r'E:\mw124\acts-perf\deps\gsc-tool\src\gsc\engine\iw8_token.cpp'
tokens = {}
with open(token_file, encoding='utf-8', errors='replace') as f:
    for m in re.finditer(r'\{\s*0x([0-9A-Fa-f]+),\s*"([^"]*)"\s*\}', f.read()):
        tokens.setdefault(int(m.group(1), 16), m.group(2))
rows = []
for zone in ('common_base_mp', 'global_mp'):
    dirs = glob.glob(os.path.join(root, 'out', 'warzone_study', zone, '**', 'scriptfile'), recursive=True)
    if not dirs:
        sys.exit('no scriptfile export of ' + zone)
    base = dirs[0]
    for path in glob.glob(os.path.join(base, '**', '*.gscbin'), recursive=True):
        rel = os.path.relpath(path, base).replace('\\', '/')
        rel = re.sub(r'\.\d+\.gscbin$', '', rel)  # ACTS adds ".<index>.gscbin"
        if re.fullmatch(r'\d+', rel):
            number = int(rel)
            name = tokens.get(number, '')
            if name.startswith('scripts/') or name.startswith('maps/'):
                rows.append((name, 'numbered', number, zone))
            else:
                rows.append(('#%d' % number, 'numbered', number, zone))  # a number gsc-tool has no path for
        else:
            rows.append((re.sub(r'\.gsc$', '', rel), 'named', 0, zone))
rows.sort()
dest = os.path.join(root, 'data', 'generated', 'iw8_stock_scripts.tsv')
with open(dest, 'w', encoding='utf-8', newline='\n') as out:
    out.write('# Stock GSC files of the always-loaded zones (common_base_mp, global_mp) and how each is named there\n')
    out.write('# (docs/research/92). Generated by tools/build_stock_script_index.py; do not edit.\n')
    out.write('# path<TAB>numbered|named<TAB>number<TAB>zone\n')
    for r in rows:
        out.write('%s\t%s\t%d\t%s\n' % r)
print('wrote %s: %d numbered, %d named' % (dest, sum(r[1] == 'numbered' for r in rows), sum(r[1] == 'named' for r in rows)))
