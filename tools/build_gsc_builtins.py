"""Writes data/generated/iw8_gsc_builtins.txt: the named IW8 GSC builtins (functions, then methods) for the editor's
Script dock (completion and highlighting, roadmap 6.11).

Source: the x64-zt fork's src/convert/iw3_iw8/iw8_gsc_builtins.inc (generated there from gsc-tool's iw8 tables and
cross-checked against the Replay 1.20 builtin tables). Unnamed ids (_func_XXX, _meth_XXX) are left out.

Usage: py -3 tools/build_gsc_builtins.py [path to iw8_gsc_builtins.inc]
"""
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else r'E:\mw124\x64-zt\src\convert\iw3_iw8\iw8_gsc_builtins.inc'
text = open(src, encoding='utf-8').read()
parts = re.split(r'kIw8GscMethods', text, maxsplit=1)
if len(parts) != 2:
    raise SystemExit('unexpected file layout: no kIw8GscMethods table')


def names(block):
    out = sorted({n for n in re.findall(r'"([a-z_][a-z0-9_]*)"', block) if not re.match(r'_(func|meth)_[0-9a-f]+$', n)})
    return out


funcs, meths = names(parts[0]), names(parts[1])
dest = os.path.join(root, 'data', 'generated', 'iw8_gsc_builtins.txt')
with open(dest, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# IW8 GSC builtins for the Script dock. Generated by tools/build_gsc_builtins.py; do not edit.\n')
    f.write('# kind<TAB>name   (f = function, m = method called on an entity)\n')
    for n in funcs:
        f.write('f\t' + n + '\n')
    for n in meths:
        f.write('m\t' + n + '\n')
print(len(funcs), 'functions,', len(meths), 'methods ->', dest)
