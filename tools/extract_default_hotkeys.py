#!/usr/bin/env python3
"""Regenerates the default hotkey preset (id "iw8radiant") in data/hotkey_presets.json from src/qtapp/main_window.cpp.

Usage, from the repo root:
    py -3 -I tools/extract_default_hotkeys.py          rewrite the default preset's keys
    py -3 -I tools/extract_default_hotkeys.py --check  exit 1 when the file is out of date (no write)

Every addCommand(menu, "<id>", "<text>", QKeySequence(<default>), ...) call is read. Literal ids are taken as written.
Ids built in loops are expanded from the loop's own template, and the script fails when a template it expects is gone,
so a changed loop is noticed instead of silently dropped. Grid commands come from the `sizes[]` table. Any other
runtime-built id (ToolMaterial_, Trigger_, ...) must have an empty default, or the run fails.

Other presets in the file (stock Radiant, iw3xo) are left untouched; they are hand-curated from the research docs.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN_WINDOW = os.path.join(ROOT, "src", "qtapp", "main_window.cpp")
PRESETS = os.path.join(ROOT, "data", "hotkey_presets.json")
DEFAULT_ID = "iw8radiant"
DEFAULT_NAME = "IW8 Radiant (default)"
DEFAULT_SOURCE = "src/qtapp/main_window.cpp addCommand() defaults (generated by tools/extract_default_hotkeys.py)"

AXES = ["X", "Y", "Z"]
# Loop-built command families: (template as written in main_window.cpp, argument lists, default key format,
# text that must appear in the call's default expression). Bookmark keys are Ctrl+1..9 and Ctrl+Shift+1..9.
FAMILIES = [
    ("CameraBookmarkGo%1", [[str(i) for i in range(1, 10)]], "Ctrl+{0}", 'QKeySequence(QString("Ctrl+%1")'),
    ("CameraBookmarkSet%1", [[str(i) for i in range(1, 10)]], "Ctrl+Shift+{0}", 'QKeySequence(QString("Ctrl+Shift+%1")'),
    ("Rotate%1", [AXES], "", "QKeySequence()"),
    ("Flip%1", [AXES], "", "QKeySequence()"),
    ("MirrorClone%1", [AXES], "", "QKeySequence()"),
    ("Align%1%2", [AXES, ["Min", "Center", "Max"]], "", "QKeySequence()"),
    ("Distribute%1", [AXES], "", "QKeySequence()"),
]

QT_KEY_NAMES = {
    "Space": "Space", "Backspace": "Backspace", "Escape": "Esc", "Return": "Return", "Enter": "Enter",
    "Tab": "Tab", "Insert": "Insert", "Delete": "Delete", "Home": "Home", "End": "End", "PageUp": "PgUp",
    "PageDown": "PgDown", "Left": "Left", "Right": "Right", "Up": "Up", "Down": "Down",
    "BracketLeft": "[", "BracketRight": "]", "Backslash": "\\", "Comma": ",", "Period": ".", "Slash": "/",
    "Semicolon": ";", "Apostrophe": "'", "QuoteLeft": "`", "Minus": "-", "Equal": "=", "Plus": "+",
}
MOD_ORDER = ["Ctrl", "Alt", "Shift", "Meta"]
MOD_ALIASES = {"Control": "Ctrl", "Ctrl": "Ctrl", "Alt": "Alt", "Shift": "Shift", "Meta": "Meta"}
NONLITERAL = object()

STR_RE = re.compile(r'^"((?:[^"\\]|\\.)*)"$', re.S)
KS_RE = re.compile(r"^QKeySequence\((.*)\)$", re.S)


def fail(msg):
    print("extract_default_hotkeys: " + msg, file=sys.stderr)
    sys.exit(2)


def unescape(s):
    return re.sub(r"\\(.)", r"\1", s)


def cstr(raw):
    m = STR_RE.match(raw)
    return unescape(m.group(1)) if m else None


def qt_key(name):
    """Qt::Key_<name> to the portable key name used in presets."""
    if name in QT_KEY_NAMES:
        return QT_KEY_NAMES[name]
    if re.fullmatch(r"[A-Z]", name) or re.fullmatch(r"[0-9]", name):
        return name
    m = re.fullmatch(r"F(\d{1,2})", name)
    if m:
        return "F" + m.group(1)
    fail("unknown Qt key Qt::Key_" + name + " (add it to QT_KEY_NAMES)")


def canon(seq):
    """Canonical portable form: modifiers in Ctrl, Alt, Shift, Meta order, then the key. '' means unbound."""
    if not seq:
        return ""
    if seq == "+":
        return "+"
    if seq.endswith("++"):
        base, key = seq[:-2], "+"
    else:
        base, _, key = seq.rpartition("+")
    mods = [m for m in base.split("+") if m] if base else []
    try:
        mods = [MOD_ALIASES[m] for m in mods]
    except KeyError as e:
        fail("unknown modifier %r in key %r" % (e.args[0], seq))
    if len(set(mods)) != len(mods) or not key:
        fail("bad key sequence %r" % seq)
    return "+".join([m for m in MOD_ORDER if m in mods] + [key])


def read_args(text, pos):
    """pos is just after the '(' of a call. Returns the top-level arguments (raw, stripped)."""
    args, cur, depth, i, n = [], [], 0, pos, len(text)
    while i < n:
        c = text[i]
        if c == '"' or c == "'":
            j = i + 1
            while text[j] != c:
                j += 2 if text[j] == "\\" else 1
            cur.append(text[i:j + 1])
            i = j + 1
            continue
        if text.startswith("//", i):
            i = text.find("\n", i)
            if i < 0:
                break
            continue
        if text.startswith("/*", i):
            i = text.find("*/", i) + 2
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                args.append("".join(cur).strip())
                return args, i
            depth -= 1
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
            i += 1
            continue
        cur.append(c)
        i += 1
    fail("unterminated addCommand call near offset %d" % pos)


def default_key(raw):
    m = KS_RE.match(raw)
    if not m:
        fail("default is not a QKeySequence expression: " + raw)
    inner = m.group(1).strip()
    if inner == "":
        return ""
    s = cstr(inner)
    if s is not None:
        return canon(s)
    k = re.fullmatch(r"Qt::Key_(\w+)", inner)
    if k:
        return canon(qt_key(k.group(1)))
    return NONLITERAL


def grid_table(text):
    m = re.search(r"const\s+G\s+sizes\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        fail("grid table `const G sizes[]` not found in main_window.cpp")
    rows = re.findall(r'\{"(\w+)",\s*[0-9.]+,\s*"((?:[^"\\]|\\.)*)"\}', m.group(1))
    if len(rows) != 11:
        fail("expected 11 grid rows, found %d" % len(rows))
    return [(cmd, canon(unescape(key))) for cmd, key in rows]


def extract(text):
    keys = {}
    seen_family = set()
    literal_calls = 0
    dynamic = 0

    def add(cid, key, where):
        if cid in keys and keys[cid] != key:
            fail("%s added twice with different defaults (%r vs %r) at %s" % (cid, keys[cid], key, where))
        keys[cid] = key

    for m in re.finditer(r"(?<![\w:])addCommand\(", text):
        args, _ = read_args(text, m.end())
        if len(args) < 4:
            fail("addCommand call with fewer than 4 arguments at offset %d" % m.start())
        where = "offset %d" % m.start()
        raw_id, raw_def = args[1], args[3]
        lit = cstr(raw_id)
        key = default_key(raw_def)
        if lit is not None:
            if key is NONLITERAL:
                fail("%s: default %s is not a literal key" % (lit, raw_def))
            add(lit, key, where)
            literal_calls += 1
            continue
        if raw_id == "g.cmd":
            if raw_def != "QKeySequence(g.key)":
                fail("grid call has unexpected default " + raw_def)
            continue  # expanded from the sizes[] table below
        fam = [f for f in FAMILIES if raw_id.startswith('QString("%s")' % f[0])]
        if fam:
            template, _, _, must = fam[0]
            if must not in raw_def:
                fail("family %s: default %s no longer matches %r" % (template, raw_def, must))
            seen_family.add(template)
            continue
        if key is not NONLITERAL and key != "":
            fail("runtime-built command %s has default %r; add its template to FAMILIES" % (raw_id, raw_def))
        dynamic += 1

    for cmd, key in grid_table(text):
        add(cmd, key, "sizes[] table")

    for template, arg_lists, fmt, must in FAMILIES:
        if 'QString("%s")' % template not in text or must not in text:
            fail("family template %r not found in main_window.cpp; update FAMILIES" % template)
        for combo in _combos(arg_lists):
            cid = template
            for i, v in enumerate(combo):
                cid = cid.replace("%%%d" % (i + 1), v)
            add(cid, fmt.format(*combo) if fmt else "", "family " + template)

    return keys, literal_calls, dynamic, sorted(seen_family)


def _combos(arg_lists):
    """Cartesian product of the argument lists, e.g. [AXES, MODES] -> ("X", "Min"), ("X", "Center"), ..."""
    combos = [()]
    for values in arg_lists:
        combos = [c + (v,) for c in combos for v in values]
    return combos


def conflicts(keys):
    by_key = {}
    for cid, key in keys.items():
        if key:
            by_key.setdefault(key, []).append(cid)
    return sorted((k, sorted(v)) for k, v in by_key.items() if len(v) > 1)


def load_presets():
    if not os.path.exists(PRESETS):
        return {"presets": []}
    with open(PRESETS, encoding="utf-8") as f:
        return json.load(f)


def main():
    check = "--check" in sys.argv[1:]
    with open(MAIN_WINDOW, encoding="utf-8") as f:
        text = f.read()
    keys, literal_calls, dynamic, families = extract(text)
    keys = dict(sorted(keys.items()))

    data = load_presets()
    presets = data.setdefault("presets", [])
    current = next((p for p in presets if p.get("id") == DEFAULT_ID), None)

    if check:
        if current is None or {k: v for k, v in current.get("keys", {}).items()} != keys:
            print("data/hotkey_presets.json default preset is out of date; run tools/extract_default_hotkeys.py")
            return 1
        print("default preset is up to date (%d commands)" % len(keys))
        return 0

    if current is None:
        current = {"id": DEFAULT_ID, "name": DEFAULT_NAME, "source": DEFAULT_SOURCE, "keys": {}}
        presets.insert(0, current)
    current["keys"] = keys

    out = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    os.makedirs(os.path.dirname(PRESETS), exist_ok=True)
    with open(PRESETS, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)

    bound = sum(1 for v in keys.values() if v)
    print("default preset: %d commands (%d bound, %d unbound)" % (len(keys), bound, len(keys) - bound))
    print("  literal addCommand calls: %d, loop families expanded: %s, runtime-built ids without defaults: %d"
          % (literal_calls, ", ".join(families), dynamic))
    for key, ids in conflicts(keys):
        print("  NOTE conflict in default preset: %s -> %s" % (key, ", ".join(ids)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
